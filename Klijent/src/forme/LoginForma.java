    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
    try{  
        
        if(txtUsername.getText().isEmpty() ||
               String.valueOf(txtPassword.getPassword()).isEmpty()){
           JOptionPane.showMessageDialog(this, "Korisnicko ime i lozinka moraju "
                        + "biti popunjeni!");
                return;
       }
       
       String username=txtUsername.getText();
       String password=String.valueOf(txtPassword.getPassword());
       
        Administrator a=new Administrator();
        a.setUsername(username);
        a.setPassword(password);
        
        Administrator administrator=KlijentKontroler.getInstance().login(a);
        Session.getInstance().setUlogovani(administrator);
        new GlavnaForma().setVisible(true);
        this.dispose();
    }catch(Exception ex){
        JOptionPane.showMessageDialog(this, ex.getMessage());
    }
        
    }//GEN-LAST:event_btnLoginActionPerformed

