    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed
    try{   
        
        if (txtIme.getText().isEmpty() || txtPrezime.getText().isEmpty()
                    || txtUsername.getText().isEmpty() 
                    || String.valueOf(txtPassword.getPassword()).isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }
        
        String ime=txtIme.getText();
        String prezime=txtPrezime.getText();
        String username=txtUsername.getText();
        String password=String.valueOf(txtPassword.getPassword());
        
        Administrator novi=new Administrator(null, ime, prezime, username, password);
        
        KlijentKontroler.getInstance().dodajAdministratora(novi);
        JOptionPane.showMessageDialog(this, "Uspesno dodat administrator.");
        this.dispose();
        
    }catch(Exception ex){
         JOptionPane.showMessageDialog(this, ex.getMessage());
    }
    }//GEN-LAST:event_btnDodajActionPerformed

