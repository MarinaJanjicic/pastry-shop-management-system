    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        int result=JOptionPane.showConfirmDialog(this,"Da li ste sigurni da zelite da "
                + "obrisete ovog administratora?", "Konfirmacija", JOptionPane.YES_NO_OPTION);
         if (result == JOptionPane.NO_OPTION) {
            return;
        }
         
        if(result==JOptionPane.YES_OPTION){
            try{
                KlijentKontroler.getInstance().obrisiAdministratora(a);
                FormaPretragaAdministratora fpa=(FormaPretragaAdministratora) getParent();
                fpa.refreshujTabelu();
                JOptionPane.showMessageDialog(this, "Uspjesno obrisan administrator.");
                this.dispose();
                
            }catch(Exception ex){
                JOptionPane.showMessageDialog(this, "Ne mozete da obrisete ovog administratora!");
            }
        }
    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        if (txtEmail.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Polje za email mora biti popunjeno!");
            return;
        }
        
        try{
            
            String ime=txtIme.getText();
            String prezime=txtPrezime.getText();
            String username=txtEmail.getText();
            String password=String.copyValueOf(txtPassword.getPassword());
            
            if(password.isEmpty()){
                password=a.getPassword();
            }
            
            a.setIme(ime);
            a.setPrezime(prezime);
            a.setUsername(username);
            a.setPassword(password);
            
            KlijentKontroler.getInstance().izmeniAdministratora(a);
            FormaPretragaAdministratora fpa=(FormaPretragaAdministratora) getParent();
            fpa.refreshujTabelu();
            JOptionPane.showMessageDialog(this, "Uspjesno izmijenjen administrator.");
            this.dispose();
            
        }catch(Exception ex){
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }

    }//GEN-LAST:event_btnIzmeniActionPerformed

