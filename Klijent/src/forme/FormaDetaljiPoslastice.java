    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
       try{
           if (txtCenaPoKomadu.getText().isEmpty() || txtNaziv.getText().isEmpty()
                    || txtOpis.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }
           
           String naziv=txtNaziv.getText();
           String opis = txtOpis.getText();
           TipPoslastice tipPoslastice=(TipPoslastice) cbmTipPoslastice.getSelectedItem();
           double cena=Double.parseDouble(txtCenaPoKomadu.getText());
           
           p.setNaziv(naziv);
           p.setOpis(opis);
           p.setTipPoslastice(tipPoslastice);
           p.setCenaPoKomadu(cena);
           
           KlijentKontroler.getInstance().izmeniPoslasticu(p);
           FormaPretragaPoslastice fpp=(FormaPretragaPoslastice) getParent();
           fpp.refreshujTabelu();
           GlavnaForma gf=(GlavnaForma) getParent();
           FormaNoviRacun fnr=new FormaNoviRacun(gf, true);
           fnr.popuniPoslastice();
            JOptionPane.showMessageDialog(this, "Uspesno izmenjena poslastica.");
            this.dispose();
           
       }catch(Exception ex){
            JOptionPane.showMessageDialog(this, ex.getMessage());
       }
    }//GEN-LAST:event_btnIzmeniActionPerformed

