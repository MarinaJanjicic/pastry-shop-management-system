    private void popuniTipovePoslastica() {
        try {
            ArrayList<TipPoslastice> tipoviPoslastica = KlijentKontroler.getInstance().vratiTipovePoslastice();

            cbmTipPoslastice.removeAllItems();

            for (TipPoslastice tipPoslastice : tipoviPoslastica) {
                cbmTipPoslastice.addItem(tipPoslastice);
            }

        } catch (Exception ex) {
            Logger.getLogger(FormaNovaPoslastica.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
