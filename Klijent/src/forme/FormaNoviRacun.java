    private void txtKolicinaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtKolicinaKeyReleased

        if (evt.getKeyChar() >= '0' && evt.getKeyChar() <= '9') {

            Poslastica p = (Poslastica) cmbPoslastice.getSelectedItem();
            int kolicina = Integer.parseInt(txtKolicina.getText());

            if (kolicina == 0) {
                txtKolicina.setText("");
                txtCenaStavke.setText("");
                return;
            }

            txtCenaStavke.setText(String.valueOf(p.getCenaPoKomadu() * kolicina));

        } else {
            txtKolicina.setText("");
            txtCenaStavke.setText("");
        }
    }//GEN-LAST:event_txtKolicinaKeyReleased

    private void cmbPoslasticeItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cmbPoslasticeItemStateChanged
      if(cmbPoslastice.getSelectedItem()!=null){
          if(txtKolicina.getText().isEmpty()){
              txtCenaStavke.setText("");
              return;
          }
          
          Poslastica p=(Poslastica) cmbPoslastice.getSelectedItem();
          int kolicina=Integer.parseInt(txtKolicina.getText());
          
          if(kolicina==0){
              txtCenaStavke.setText("");
              txtCenaStavke.setText("");
              return;
          }
          
          txtCenaStavke.setText(String.valueOf(p.getCenaPoKomadu()*kolicina));
      }
    }//GEN-LAST:event_cmbPoslasticeItemStateChanged

    private void btnDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuActionPerformed
       if(txtKolicina.getText().isEmpty()){
           JOptionPane.showMessageDialog(this, "Kolicina mora biti popunjena!");
            return;
       }
       
       Poslastica p=(Poslastica) cmbPoslastice.getSelectedItem();
       int kolicina=Integer.parseInt(txtKolicina.getText());
       double cenaStavke=Double.parseDouble(txtCenaStavke.getText());
       
        StavkaRacuna sr=new StavkaRacuna(null, -1, kolicina, cenaStavke, p);
        
        ModelTabeleStavke mt=(ModelTabeleStavke) tblStavkeRacuna.getModel();
        mt.dodajStavku(sr);
        
        cena=mt.vratiCenu();
        lblCena.setText(String.valueOf(cena)+" RSD");
        
    }//GEN-LAST:event_btnDodajStavkuActionPerformed

    private void btnObrisiStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiStavkuActionPerformed
       int row = tblStavkeRacuna.getSelectedRow();

        if (row >= 0) {
            ModelTabeleStavke tm =  (ModelTabeleStavke) tblStavkeRacuna.getModel();
            tm.obrisiStavku(row);

            cena = tm.vratiCenu();
            lblCena.setText(String.valueOf(cena) + " RSD");
        }
    }//GEN-LAST:event_btnObrisiStavkuActionPerformed

    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed
       try{
           ModelTabeleStavke mt=(ModelTabeleStavke) tblStavkeRacuna.getModel();
           
           Racun r=new Racun(null, new Date(), cena, ulogovani, mt.getLista());
           
           KlijentKontroler.getInstance().sacuvajRacun(r);
           resetujFormu();
           JOptionPane.showMessageDialog(this, "Uspesno sacuvan racun!");
       }catch(Exception ex){
           JOptionPane.showMessageDialog(this, ex.getMessage());
       }
    }//GEN-LAST:event_btnSacuvajActionPerformed

