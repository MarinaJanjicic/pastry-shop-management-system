    public void popuniPoslastice() {
         try {
            ArrayList<Poslastica> poslastice = KlijentKontroler.getInstance().vratiPoslastice(null);

            cmbPoslastice.removeAllItems();

            for (Poslastica poslastica : poslastice) {
                cmbPoslastice.addItem(poslastica);
            }

        } catch (Exception ex) {
            Logger.getLogger(FormaNovaPoslastica.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    private void resetujFormu() {
       txtKolicina.setText("");
        txtCenaStavke.setText("");
        lblCena.setText("0.00din");
        cena = 0;
        ModelTabeleStavke tm = (ModelTabeleStavke) tblStavkeRacuna.getModel();
        tm.getLista().clear();
        tm.fireTableDataChanged();
    }
